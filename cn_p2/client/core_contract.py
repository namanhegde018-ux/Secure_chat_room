"""Typed contract expected by the GUI; Name 1's Core adapter can implement this."""

from typing import Protocol, Any


class CoreEventSink(Protocol):
    def on_invite_received(self, event: dict[str, Any]) -> None: ...
    def on_session_started(self, event: dict[str, Any]) -> None: ...
    def on_message(self, event: dict[str, Any]) -> None: ...
    def on_file_received(self, event: dict[str, Any]) -> None: ...
    def on_export_request(self, event: dict[str, Any]) -> None: ...
    def on_export_decision(self, event: dict[str, Any]) -> None: ...
    def on_peer_disconnected(self, event: dict[str, Any]) -> None: ...
    def on_session_ended(self, event: dict[str, Any]) -> None: ...


class ClientCore(Protocol):
    def __init__(self, event_sink: CoreEventSink) -> None: ...
    def connect(self) -> None: ...
    def invite(self, peer: str) -> None: ...
    def accept(self, request: dict[str, Any]) -> None: ...
    def reject(self, request: dict[str, Any]) -> None: ...
    def send_message(self, message: str) -> None: ...
    def send_file(self, path: str) -> None: ...
    def request_export(self, name: str) -> None: ...
    def decide_export(self, request: dict[str, Any], approved: bool) -> None: ...
    def end_session(self) -> None: ...
